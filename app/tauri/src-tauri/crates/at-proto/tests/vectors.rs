//! Golden wire vectors, shared with future codecs (Route B's Swift
//! codec validates against the same file — app/design/proto-vectors/).
//!
//! Each vector is {name, direction, frame_hex, meaning}. This test
//! regenerates the client→daemon vectors from the encoders and fails on
//! any drift; REGEN_VECTORS=1 rewrites the file (then commit it, same
//! contract as the C repo's REGEN_GOLDEN).

use at_proto::*;
use std::fmt::Write as _;

fn hex(b: &[u8]) -> String {
    b.iter().fold(String::new(), |mut s, x| {
        let _ = write!(s, "{x:02x}");
        s
    })
}

