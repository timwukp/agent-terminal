#[test]
fn vectors_match_committed_golden() {
    // Inside the crate so tools that copy only the Cargo workspace
    // (cargo-mutants) still see it; app/design/proto-vectors/ points here.
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/data/client-frames.json");
    let mut arr = Vec::new();
    for (name, dir, frame, meaning) in vectors() {
        arr.push(serde_json::json!({
            "name": name,
            "direction": dir,
            "frame_hex": hex(&frame),
            "meaning": meaning,
        }));
    }
    let generated = serde_json::to_string_pretty(&serde_json::json!({
        "comment": "Golden wire frames for agent-terminal protocol codecs. \
                    Generated by at-proto tests/vectors.rs (REGEN_VECTORS=1); \
                    Route B's Swift codec must produce/parse these same bytes.",
        "vectors": arr,
    }))
    .unwrap()
        + "\n";

    if std::env::var("REGEN_VECTORS").as_deref() == Ok("1") {
        std::fs::write(path, &generated).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(path)
        .expect("committed vectors missing — run with REGEN_VECTORS=1 and commit");
    assert_eq!(
        committed, generated,
        "wire vectors drifted from the committed golden — if deliberate, REGEN_VECTORS=1 and commit"
    );
}
