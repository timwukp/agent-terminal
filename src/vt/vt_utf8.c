uint32_t vt_utf8_step(uint32_t *state, uint32_t *cp, uint8_t byte) {
    uint32_t type = utf8d[byte];
    *cp = (*state != UTF8_ACCEPT) ? (byte & 0x3fu) | (*cp << 6)
                                  : (0xffu >> type) & byte;
    *state = utf8d[256 + *state + type];
    return *state;
}
